// Експортуємо union-тип ProductCategory, який обмежує список допустимих категорій товарів
export type ProductCategory =
  | "Електроніка" // Категорія для ноутбуків, годинників та іншої електроніки
  | "Аудіо" // Категорія для навушників і колонок
  | "Смарт-дім" // Категорія для пристроїв розумного дому
  | "Аксесуари"; // Категорія для периферії та аксесуарів

// Експортуємо інтерфейс Product, який описує структуру об'єкта одного товару
export interface Product {
  id: number; // Унікальний числовий ідентифікатор товару
  name: string; // Назва товару
  price: number; // Ціна товару в гривнях (число)
  category: ProductCategory; // Категорія товару (одне зі значень типу ProductCategory)
  inStock: boolean; // Статус наявності: true — в наявності, false — немає в наявності
  isOnSale: boolean; // Чи бере товар участь в акції (зі знижкою)
  oldPrice?: number; // Необов'язкова стара ціна до знижки (у гривнях)
  description: string; // Короткий опис характеристик товару
} // Завершення оголошення інтерфейсу Product
